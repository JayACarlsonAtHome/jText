#!/usr/bin/env python3
# File:    tools/gen_unicode_ps_table.py
# Purpose: Generate src/parser/unicode_ps_table.hpp, the code point ranges whose Unicode
#          General Category is Punctuation (P*) or Symbol (S*): the characters a jText
#          formatter may use (SPEC 3.1, v0.8). Uses Python's unicodedata; the Unicode
#          version is recorded in the output. Run from the version directory:
#            python3 tools/gen_unicode_ps_table.py
import sys
import unicodedata

ranges, start = [], None
for cp in range(0x110000):
    ok = unicodedata.category(chr(cp))[0] in "PS"
    if ok and start is None:
        start = cp
    if not ok and start is not None:
        ranges.append((start, cp - 1))
        start = None

lines = [
    "// File:    src/parser/unicode_ps_table.hpp",
    "// Purpose: GENERATED by tools/gen_unicode_ps_table.py - do not edit.",
    f"//          Unicode {unicodedata.unidata_version}: code point ranges whose General Category is",
    "//          Punctuation (P*) or Symbol (S*), the characters a formatter may use (SPEC 3.1).",
    "#pragma once",
    "",
    "#include <array>",
    "",
    "namespace jtext {",
    "",
    "struct code_point_range {",
    "    char32_t first;",
    "    char32_t last;",
    "};",
    "",
    f"inline constexpr std::string_view kUnicodeVersion = \"{unicodedata.unidata_version}\";",
    "",
    f"inline constexpr std::array<code_point_range, {len(ranges)}> kPunctuationOrSymbol{{{{",
]
lines += [f"    {{0x{a:04X}, 0x{b:04X}}}," for a, b in ranges]
lines += ["}};", "", "}  // namespace jtext", ""]
out = "src/parser/unicode_ps_table.hpp"
open(out, "w").write("\n".join(lines))
print(f"wrote {out}: {len(ranges)} ranges, Unicode {unicodedata.unidata_version}", file=sys.stderr)
